export function getExerciseImageUrls(exerciseName: string): { frame0: string; frame1: string } | null {
  const id = EXERCISE_IMAGE_IDS[exerciseName];
  if (!id) return null;
  return {
    frame0: `${EXERCISE_IMAGE_BASE}/${id}/0.jpg`,
    frame1: `${EXERCISE_IMAGE_BASE}/${id}/1.jpg`,
  };
}
